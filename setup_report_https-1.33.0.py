"""生成仅 IP 使用的 HTTPS 证书及 Nginx 配置，不修改系统配置或启动服务。"""
import argparse
import hashlib
import ipaddress
from pathlib import Path
import shutil
import subprocess
import tempfile
from urllib.parse import urlsplit

def nginx_config(ip, port, upstream, directory):
    return f'''# Generated by astrbot_plugin_battle_report. Import ca.crt on client devices.
server {{
    listen {port} ssl;
    server_name {ip};
    ssl_certificate "{directory}/server.crt";
    ssl_certificate_key "{directory}/server.key";
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 1m;
    add_header Cache-Control "no-store" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "no-referrer" always;
    proxy_set_header Host $http_host;
    proxy_set_header X-Forwarded-Proto https;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_connect_timeout 5s;
    proxy_read_timeout 75s;
    proxy_send_timeout 75s;

    location = / {{ return 302 /battle-report/; }}
    location = /battle-report {{ return 308 /battle-report/; }}
    location = /battle-report-ca.crt {{ alias "{directory}/ca.crt"; }}
    location ^~ /battle-report/ {{
        limit_except GET POST {{ deny all; }}
        proxy_buffering off;
        proxy_pass {upstream};
    }}
    location = /api/auth/login {{
        limit_except POST {{ deny all; }}
        proxy_pass {upstream};
    }}
    location = /api/auth/logout {{
        limit_except POST {{ deny all; }}
        proxy_pass {upstream};
    }}
    location ^~ /api/plug/astrbot_plugin_battle_report/comparison/ {{
        limit_except GET POST {{ deny all; }}
        proxy_buffering off;
        proxy_pass {upstream};
    }}
    location / {{ return 404; }}
}}
'''


def generate(ip, output, *, port=8443, upstream='http://127.0.0.1:6185'):
    ip=str(ipaddress.IPv4Address(ip))
    if type(port) is not int or not 1<=port<=65535:raise ValueError('HTTPS端口无效。')
    parsed=urlsplit(upstream)
    if (parsed.scheme!='http' or not parsed.hostname or parsed.username or parsed.password
            or parsed.path not in ('','/') or parsed.query or parsed.fragment):raise ValueError('后端应为本机或内网的HTTP地址，不含路径和认证参数。')
    # Only a host and port enter the generated Nginx directive.
    import re
    if not re.fullmatch(r'[A-Za-z0-9.-]+',parsed.hostname):raise ValueError('后端主机名无效。')
    try:
        address=ipaddress.ip_address(parsed.hostname)
        internal=address.is_loopback or address.is_private
    except ValueError:
        internal='.' not in parsed.hostname or parsed.hostname.endswith(('.internal','.local'))
    if not internal:raise ValueError('HTTP后端必须位于本机或内网。')
    backend_port=parsed.port if parsed.port is not None else 80
    if not 1<=backend_port<=65535:raise ValueError('后端端口无效。')
    upstream=f'http://{parsed.hostname}:{backend_port}'
    output=Path(output).expanduser().resolve()
    # The script may be copied out of the plugin before running (docker cp).
    # Detect plugin roots by their files, rather than treating /tmp's parent as one.
    if any((parent/'metadata.yaml').is_file() and (parent/'main.py').is_file() for parent in [output,*output.parents]):
        raise ValueError('证书目录必须位于插件目录之外。')
    if any(c in str(output) for c in ('"','\n','\r','$','\\')):raise ValueError('证书目录不能包含引号、换行、反斜线或美元符号。')
    if output.exists() and (not output.is_dir() or any(output.iterdir())):raise ValueError('输出目录非空，请使用新的目录，勿覆盖现有证书。')
    executable=shutil.which('openssl')
    if not executable:raise ValueError('请先安装OpenSSL后重试。')
    output.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.report-https-',dir=output.parent) as temporary:
        stage=Path(temporary)/'https';stage.mkdir()
        def run(*args):
            subprocess.run([executable,*args],cwd=stage,check=True,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,timeout=60)
        run('req','-x509','-newkey','rsa:3072','-nodes','-sha256','-days','3650',
            '-keyout','ca.key','-out','ca.crt','-subj','/CN=Battle Report Private CA',
            '-addext','basicConstraints=critical,CA:TRUE,pathlen:0',
            '-addext','keyUsage=critical,keyCertSign,cRLSign')
        run('req','-new','-newkey','rsa:2048','-nodes','-sha256','-keyout','server.key','-out','server.csr','-subj','/CN='+ip)
        extensions=stage/'server.ext'
        extensions.write_text('basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=IP:'+ip+'\n')
        run('x509','-req','-in','server.csr','-CA','ca.crt','-CAkey','ca.key','-CAcreateserial',
            '-out','server.crt','-days','365','-sha256','-extfile','server.ext')
        for name in ('server.csr','server.ext','ca.srl'):(stage/name).unlink(missing_ok=True)
        (stage/'battle-report-ip-https.conf').write_text(nginx_config(ip,port,upstream,output))
        for file in stage.iterdir():file.chmod(0o600 if file.suffix=='.key' else 0o644)
        stage.chmod(0o755)
        if output.exists():output.rmdir()
        stage.rename(output)
    fingerprint=subprocess.check_output([executable,'x509','-in',str(output/'ca.crt'),'-noout','-fingerprint','-sha256'],text=True).strip()
    return dict(ip=ip,port=port,output=output,fingerprint=fingerprint,
                ca_file_sha256=hashlib.sha256((output/'ca.crt').read_bytes()).hexdigest(),
                url=f'https://{ip}'+(f':{port}' if port!=443 else '')+'/battle-report/')


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ip',required=True,help='服务器公网IPv4地址')
    parser.add_argument('--output',type=Path,required=True,help='新建或为空的证书目录，位于插件目录外')
    parser.add_argument('--https-port',type=int,default=8443,help='独立HTTPS端口，默认8443，需确认未占用并开放防火墙')
    parser.add_argument('--upstream',default='http://127.0.0.1:6185',help='本机／内网AstrBot后端地址')
    args=parser.parse_args()
    try:result=generate(args.ip,args.output,port=args.https_port,upstream=args.upstream)
    except (ValueError,OSError,subprocess.SubprocessError) as error:parser.exit(1,f'生成失败：{error}\n')
    print('已生成HTTPS证书及配置：',result['output'])
    print('访问地址：',result['url'])
    print('客户端需导入信任 ca.crt；通过服务器终端核对以下指纹：')
    print(result['fingerprint'])
    print('ca.crt 文件SHA256：',result['ca_file_sha256'])
    print('将 battle-report-ip-https.conf 安装到 Nginx 后，先 nginx -t，再重载；允许所选HTTPS端口。')
    print('私钥 ca.key、server.key 仅保存在服务器，勿上传或公开。服务器证书有效期365天。')


if __name__=='__main__':main()
